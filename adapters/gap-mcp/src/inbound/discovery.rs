const MAX_SYNOPSIS_BYTES: usize = 90;
const ABSTENTION_THRESHOLD: f64 = 0.15;

fn is_graphql_builtin_scalar(name: &str) -> bool {
    matches!(name, "Int" | "Float" | "String" | "Boolean" | "ID")
}

fn is_root_type(name: &str) -> bool {
    matches!(name, "Query" | "Mutation" | "Subscription")
}

fn is_gap_or_graphql_builtin_type(name: &str) -> bool {
    name.starts_with("__")
        || is_graphql_builtin_scalar(name)
        || is_root_type(name)
        || RESERVED_BUILTIN_TYPES.contains(&name)
}

fn directive_branch_id(directives: &apollo_compiler::schema::DirectiveList) -> Option<&str> {
    for dir in directives {
        if dir.name.as_str() == "branch" {
            for arg in &dir.arguments {
                if arg.name.as_str() == "id"
                    && let ast::Value::String(s) = &*arg.value
                {
                    return Some(s.as_str());
                }
            }
        }
    }
    None
}

fn find_branch_by_slug<'a>(snapshot: &'a Snapshot, slug: &str) -> Option<&'a BranchDescriptor> {
    snapshot
        .branches
        .values()
        .find(|b| b.id.as_str() == slug)
        .map(std::convert::AsRef::as_ref)
}

/// Resolves the owning [`BranchDescriptor`] of a schema type, if branch-scoped.
pub(crate) fn resolve_type_branch<'a>(
    snapshot: &'a Snapshot,
    type_name: &str,
) -> Option<&'a BranchDescriptor> {
    if is_gap_or_graphql_builtin_type(type_name) {
        return None;
    }

    if let Some(ext_ty) = snapshot.schema.types.get(type_name) {
        let dir_slug = match ext_ty {
            ExtendedType::Object(o) => directive_branch_id(&o.directives),
            ExtendedType::Interface(i) => directive_branch_id(&i.directives),
            ExtendedType::InputObject(inp) => directive_branch_id(&inp.directives),
            ExtendedType::Enum(e) => directive_branch_id(&e.directives),
            ExtendedType::Union(u) => directive_branch_id(&u.directives),
            ExtendedType::Scalar(s) => directive_branch_id(&s.directives),
        };
        if let Some(slug) = dir_slug
            && let Some(branch) = find_branch_by_slug(snapshot, slug)
        {
            return Some(branch);
        }
    }

    for (coord, uid) in snapshot.ownership.iter() {
        if coord.type_name == type_name
            && let Some(branch) = snapshot.branches.get(uid)
        {
            return Some(branch.as_ref());
        }
    }

    // Fallback to longest `{ns}_` prefix match generated by `gap_snapshot::compose`.
    let mut best: Option<(usize, &BranchDescriptor)> = None;
    for branch in snapshot.branches.values() {
        let ns = branch.id.as_str().replace('-', "_");
        if type_name.len() > ns.len() + 1
            && type_name.starts_with(&ns)
            && type_name.as_bytes().get(ns.len()) == Some(&b'_')
        {
            let prefix_len = ns.len() + 1;
            if best.is_none_or(|(prev_len, _)| prefix_len > prev_len) {
                best = Some((prefix_len, branch.as_ref()));
            }
        }
    }
    best.map(|(_, b)| b)
}

fn resolve_field_branch<'a>(
    snapshot: &'a Snapshot,
    parent_type: &str,
    field_name: &str,
) -> Option<&'a BranchDescriptor> {
    if let Some(uid) = snapshot
        .ownership
        .owner(&FieldCoordinate::new(parent_type, field_name))
        && let Some(branch) = snapshot.branches.get(&uid)
    {
        return Some(branch.as_ref());
    }
    resolve_type_branch(snapshot, parent_type)
}

pub(crate) fn is_branch_visible(
    ctx: &RequestContext,
    visibility: &dyn Visibility,
    branch: &BranchDescriptor,
) -> bool {
    visibility.visible(ctx, ElementRef::Branch(branch))
}

pub(crate) fn is_type_visible(
    ctx: &RequestContext,
    visibility: &dyn Visibility,
    snapshot: &Snapshot,
    type_name: &str,
) -> bool {
    if type_name.starts_with("__") {
        return false;
    }
    let branch = resolve_type_branch(snapshot, type_name);
    if let Some(b) = branch
        && !is_branch_visible(ctx, visibility, b)
    {
        return false;
    }
    visibility.visible(
        ctx,
        ElementRef::Type {
            name: type_name,
            branch,
        },
    )
}

fn is_field_visible(
    ctx: &RequestContext,
    visibility: &dyn Visibility,
    snapshot: &Snapshot,
    parent_type: &str,
    field_name: &str,
    return_inner_type: &str,
) -> bool {
    let branch = resolve_field_branch(snapshot, parent_type, field_name);
    if let Some(b) = branch
        && !is_branch_visible(ctx, visibility, b)
    {
        return false;
    }
    if !visibility.visible(
        ctx,
        ElementRef::Field {
            type_name: parent_type,
            field_name,
            branch,
        },
    ) {
        return false;
    }
    is_graphql_builtin_scalar(return_inner_type)
        || is_type_visible(ctx, visibility, snapshot, return_inner_type)
}

/// Renders the `GQL-023` L0 supergraph overview JSON (`gap_describe{overview:true}` and `gap://meta`).
pub(crate) fn render_overview_json(inner: &FacadeInner, ctx: &RequestContext) -> Value {
    let vis = inner.visibility.as_ref();
    let mut visible_uids: HashSet<BranchUid> = HashSet::new();
    let mut visible_branches: Vec<&BranchDescriptor> = Vec::new();
    for (uid, desc) in &ctx.snapshot.branches {
        if is_branch_visible(ctx, vis, desc) {
            visible_uids.insert(*uid);
            visible_branches.push(desc.as_ref());
        }
    }

    // Order by operation count descending, then branch id ascending (`GQL-023`).
    visible_branches.sort_by(|a, b| {
        b.operations
            .len()
            .cmp(&a.operations.len())
            .then_with(|| a.id.as_str().cmp(b.id.as_str()))
    });
    visible_branches.truncate(inner.config.metagraph_branches);

    let branch_items: Vec<Value> = visible_branches
        .into_iter()
        .map(|b| {
            let cut = floor_utf8_boundary(&b.synopsis, MAX_SYNOPSIS_BYTES);
            let clamped = &b.synopsis[..cut];
            json!({
                "id": b.id.as_str(),
                "synopsis": clamped,
                "operationCount": b.operations.len(),
                "trust": b.trust,
                "status": b.status,
            })
        })
        .collect();

    let group_count = ctx
        .snapshot
        .groups
        .values()
        .filter(|g| {
            g.members
                .iter()
                .any(|(buid, _)| visible_uids.contains(buid))
        })
        .count();

    let prelim = json!({
        "generation": ctx.snapshot.generation,
        "branches": branch_items,
        "groupCount": group_count,
    });
    let prelim_str = serde_json::to_string(&prelim).unwrap_or_default();
    let tokens_est = estimate_tokens_gql022(&prelim_str);

    json!({
        "generation": ctx.snapshot.generation,
        "branches": prelim["branches"],
        "groupCount": group_count,
        "tokensEstimate": tokens_est,
    })
}

/// Renders visible persisted operations (`gap_describe{operations:true}` and `gap://operations`).
pub(crate) fn render_operations_json(inner: &FacadeInner, ctx: &RequestContext) -> Value {
    let vis = inner.visibility.as_ref();
    let ops: Vec<Value> = inner
        .operations
        .list(ctx)
        .into_iter()
        .filter(|op| vis.visible(ctx, ElementRef::Operation(op)))
        .filter_map(|op| serde_json::to_value(op).ok())
        .collect();
    Value::Array(ops)
}

fn render_single_visible_type_sdl(
    ctx: &RequestContext,
    visibility: &dyn Visibility,
    snapshot: &Snapshot,
    type_name: &str,
) -> Option<(String, Vec<String>)> {
    let ext_ty = snapshot.schema.types.get(type_name)?;
    let mut cloned = ext_ty.clone();
    let mut referenced: BTreeSet<String> = BTreeSet::new();

    let mut push_ref = |name: &str| {
        if !is_graphql_builtin_scalar(name)
            && !name.starts_with("__")
            && snapshot.schema.types.contains_key(name)
            && is_type_visible(ctx, visibility, snapshot, name)
        {
            referenced.insert(name.to_owned());
        }
    };

    match &mut cloned {
        ExtendedType::Object(obj_node) => {
            let obj = obj_node.make_mut();
            obj.implements_interfaces
                .retain(|iface| is_type_visible(ctx, visibility, snapshot, iface.name.as_str()));
            for iface in &obj.implements_interfaces {
                push_ref(iface.name.as_str());
            }
            let mut kept = apollo_compiler::collections::IndexMap::default();
            for (fname, fdef) in &obj.fields {
                let ret_name = fdef.ty.inner_named_type().as_str();
                if !is_field_visible(
                    ctx,
                    visibility,
                    snapshot,
                    type_name,
                    fname.as_str(),
                    ret_name,
                ) {
                    continue;
                }
                if fdef.arguments.iter().any(|arg| {
                    let arg_ty = arg.ty.inner_named_type().as_str();
                    !is_graphql_builtin_scalar(arg_ty)
                        && !is_type_visible(ctx, visibility, snapshot, arg_ty)
                }) {
                    continue;
                }
                push_ref(ret_name);
                for arg in &fdef.arguments {
                    push_ref(arg.ty.inner_named_type().as_str());
                }
                kept.insert(fname.clone(), fdef.clone());
            }
            obj.fields = kept;
        }
        ExtendedType::Interface(iface_node) => {
            let iface = iface_node.make_mut();
            iface
                .implements_interfaces
                .retain(|i| is_type_visible(ctx, visibility, snapshot, i.name.as_str()));
            for i in &iface.implements_interfaces {
                push_ref(i.name.as_str());
            }
            let mut kept = apollo_compiler::collections::IndexMap::default();
            for (fname, fdef) in &iface.fields {
                let ret_name = fdef.ty.inner_named_type().as_str();
                if !is_field_visible(
                    ctx,
                    visibility,
                    snapshot,
                    type_name,
                    fname.as_str(),
                    ret_name,
                ) {
                    continue;
                }
                push_ref(ret_name);
                for arg in &fdef.arguments {
                    push_ref(arg.ty.inner_named_type().as_str());
                }
                kept.insert(fname.clone(), fdef.clone());
            }
            iface.fields = kept;
        }
        ExtendedType::InputObject(inp_node) => {
            let inp = inp_node.make_mut();
            let mut kept = apollo_compiler::collections::IndexMap::default();
            for (fname, fdef) in &inp.fields {
                let fty = fdef.ty.inner_named_type().as_str();
                if !is_field_visible(ctx, visibility, snapshot, type_name, fname.as_str(), fty) {
                    continue;
                }
                push_ref(fty);
                kept.insert(fname.clone(), fdef.clone());
            }
            inp.fields = kept;
        }
        ExtendedType::Union(uni_node) => {
            let uni = uni_node.make_mut();
            uni.members
                .retain(|m| is_type_visible(ctx, visibility, snapshot, m.name.as_str()));
            for m in &uni.members {
                push_ref(m.name.as_str());
            }
        }
        ExtendedType::Enum(_) | ExtendedType::Scalar(_) => {}
    }

    let sdl = cloned.to_string().trim().to_owned();
    Some((sdl, referenced.into_iter().collect()))
}

/// Renders cycle-safe GraphQL SDL for `requested_types` expanded to `depth` (`1..=3`, `GQL-024`, `GQL-062`).
pub(crate) fn render_types_sdl(
    inner: &FacadeInner,
    ctx: &RequestContext,
    requested_types: &[String],
    depth: usize,
) -> Result<String, GapError> {
    let vis = inner.visibility.as_ref();
    let snap = &ctx.snapshot;

    for tname in requested_types {
        if !snap.schema.types.contains_key(tname.as_str())
            || !is_type_visible(ctx, vis, snap, tname.as_str())
        {
            let visible_names: Vec<String> = snap
                .schema
                .types
                .keys()
                .map(|n| n.as_str())
                .filter(|n| !n.starts_with("__") && is_type_visible(ctx, vis, snap, n))
                .map(str::to_owned)
                .collect();
            let dym =
                gap_ql::rank_did_you_mean(tname.as_str(), visible_names.iter().map(String::as_str));
            let mut err = GapError::new(ErrorCode::UnknownField, format!("unknown type `{tname}`"));
            if !dym.is_empty() {
                err = err.with_suggestion(Suggestion {
                    did_you_mean: Some(dym),
                    ..Suggestion::default()
                });
            }
            return Err(err);
        }
    }

    let mut visited: HashSet<String> = HashSet::new();
    let mut frontier: Vec<String> = Vec::new();
    for tname in requested_types {
        if visited.insert(tname.clone()) {
            frontier.push(tname.clone());
        }
    }

    let mut rendered_blocks: Vec<String> = Vec::new();
    let max_level = depth.clamp(1, 3);

    for level in 1..=max_level {
        let mut next_frontier_set: BTreeSet<String> = BTreeSet::new();
        for ty_name in &frontier {
            if let Some((sdl, refs)) = render_single_visible_type_sdl(ctx, vis, snap, ty_name) {
                rendered_blocks.push(sdl);
                if level < max_level {
                    for r in refs {
                        if !visited.contains(&r) {
                            next_frontier_set.insert(r);
                        }
                    }
                }
            }
        }
        frontier.clear();
        for next_ty in next_frontier_set {
            if visited.insert(next_ty.clone()) {
                frontier.push(next_ty);
            }
        }
        if frontier.is_empty() {
            break;
        }
    }

    Ok(rendered_blocks.join("\n\n"))
}

/// Executes `gap_describe` (`CMP-002`, `GQL-023`, `GQL-024`, `GQL-061`, `GQL-062`).
pub(crate) fn execute_gap_describe(
    inner: &FacadeInner,
    ctx: &RequestContext,
    era: WireEra,
    overview: Option<bool>,
    types: Option<&[String]>,
    depth: usize,
    operations: Option<bool>,
) -> Value {
    let default_overview =
        overview.is_none() && types.is_none_or(<[String]>::is_empty) && operations.is_none();
    let want_overview = overview.unwrap_or(default_overview);
    let want_ops = operations.unwrap_or(false);

    let mut data_map = Map::new();
    if want_overview {
        data_map.insert("overview".to_owned(), render_overview_json(inner, ctx));
    }
    if let Some(req_types) = types
        && !req_types.is_empty()
    {
        match render_types_sdl(inner, ctx, req_types, depth) {
            Ok(sdl) => {
                data_map.insert("sdl".to_owned(), json!(sdl));
            }
            Err(gap_err) => {
                return build_gap_error_tool_result(
                    &inner.config,
                    era,
                    &ctx.snapshot,
                    gap_err,
                    None,
                );
            }
        }
    }
    if want_ops {
        data_map.insert("operations".to_owned(), render_operations_json(inner, ctx));
    }

    build_data_tool_result(
        &inner.config,
        era,
        &ctx.snapshot,
        Value::Object(data_map),
        Map::new(),
        None,
    )
}

#[derive(Debug, Clone)]
struct SearchCandidate {
    kind: &'static str,
    name: String,
    path: String,
    branch: Option<String>,
    description: Option<String>,
    sdl: String,
    primary_type: String,
    side_effect: Option<SideEffectLevel>,
    trust: Option<TrustTier>,
    tokens: Vec<String>,
}

fn split_identifier_and_text_tokens(text: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let mut cur = String::new();
    let mut prev_is_lower = false;

    for ch in text.chars() {
        if ch.is_alphanumeric() {
            let is_upper = ch.is_uppercase();
            if is_upper && prev_is_lower && !cur.is_empty() {
                out.push(cur.to_ascii_lowercase());
                cur.clear();
            }
            cur.push(ch);
            prev_is_lower = ch.is_lowercase();
        } else {
            if !cur.is_empty() {
                out.push(cur.to_ascii_lowercase());
                cur.clear();
            }
            prev_is_lower = false;
        }
    }
    if !cur.is_empty() {
        out.push(cur.to_ascii_lowercase());
    }
    out
}

fn collect_visible_search_candidates(
    inner: &FacadeInner,
    ctx: &RequestContext,
) -> BTreeMap<String, SearchCandidate> {
    let vis = inner.visibility.as_ref();
    let snap = &ctx.snapshot;
    let mut map: BTreeMap<String, SearchCandidate> = BTreeMap::new();

    // 1. Visible branch operations
    for branch in snap.branches.values() {
        if !is_branch_visible(ctx, vis, branch) {
            continue;
        }
        for op in &branch.operations {
            let root_type = match op.kind {
                OpKind::Query => "Query",
                OpKind::Mutation => "Mutation",
                OpKind::Subscription => "Subscription",
                OpKind::Task => "GapMutation",
            };
            let op_name = op
                .id
                .as_str()
                .split_once('.')
                .map_or(op.id.as_str(), |(_, n)| n);

            let (field_desc, field_sdl, ret_type) = snap
                .schema
                .types
                .get(root_type)
                .and_then(|ext| match ext {
                    ExtendedType::Object(o) => o.fields.get(op_name),
                    _ => None,
                })
                .map_or_else(
                    || (None, op.sdl.to_string(), root_type.to_owned()),
                    |fdef| {
                        let rname = fdef.ty.inner_named_type().as_str().to_owned();
                        if !is_field_visible(ctx, vis, snap, root_type, op_name, &rname) {
                            return (None, String::new(), String::new());
                        }
                        let desc = fdef.description.as_ref().map(|d| d.as_str().to_owned());
                        let mut sig =
                            format!("type {root_type} {{\n  {}\n}}", fdef.to_string().trim());
                        if !is_gap_or_graphql_builtin_type(&rname)
                            && let Some((ty_sdl, _)) =
                                render_single_visible_type_sdl(ctx, vis, snap, &rname)
                        {
                            sig.push('\n');
                            sig.push_str(&ty_sdl);
                        }
                        (desc, sig, rname)
                    },
                );

            if field_sdl.is_empty() {
                continue;
            }

            let path = format!("{root_type}.{op_name}");
            let primary_type = if is_gap_or_graphql_builtin_type(&ret_type) {
                root_type.to_owned()
            } else {
                ret_type
            };

            let mut tokens = split_identifier_and_text_tokens(op_name);
            tokens.extend(split_identifier_and_text_tokens(branch.id.as_str()));
            if let Some(d) = &field_desc {
                tokens.extend(split_identifier_and_text_tokens(d));
            }

            map.insert(
                path.clone(),
                SearchCandidate {
                    kind: "OPERATION",
                    name: op_name.to_owned(),
                    path,
                    branch: Some(branch.id.as_str().to_owned()),
                    description: field_desc,
                    sdl: field_sdl,
                    primary_type,
                    side_effect: Some(op.side_effect.level),
                    trust: Some(branch.trust),
                    tokens,
                },
            );
        }
    }

    // 2. Visible user schema types and their fields
    for (ty_name_node, ext_ty) in &snap.schema.types {
        let ty_name = ty_name_node.as_str();
        if is_gap_or_graphql_builtin_type(ty_name) || !is_type_visible(ctx, vis, snap, ty_name) {
            continue;
        }
        let branch = resolve_type_branch(snap, ty_name);
        let branch_slug = branch.map(|b| b.id.as_str().to_owned());
        let trust = branch.map(|b| b.trust);

        let Some((ty_sdl, _)) = render_single_visible_type_sdl(ctx, vis, snap, ty_name) else {
            continue;
        };
        let ty_desc = match ext_ty {
            ExtendedType::Object(o) => o.description.as_ref().map(|d| d.as_str().to_owned()),
            ExtendedType::Interface(i) => i.description.as_ref().map(|d| d.as_str().to_owned()),
            ExtendedType::InputObject(inp) => {
                inp.description.as_ref().map(|d| d.as_str().to_owned())
            }
            ExtendedType::Enum(e) => e.description.as_ref().map(|d| d.as_str().to_owned()),
            ExtendedType::Union(u) => u.description.as_ref().map(|d| d.as_str().to_owned()),
            ExtendedType::Scalar(s) => s.description.as_ref().map(|d| d.as_str().to_owned()),
        };

        let mut ty_tokens = split_identifier_and_text_tokens(ty_name);
        if let Some(d) = &ty_desc {
            ty_tokens.extend(split_identifier_and_text_tokens(d));
        }
        map.insert(
            ty_name.to_owned(),
            SearchCandidate {
                kind: "TYPE",
                name: ty_name.to_owned(),
                path: ty_name.to_owned(),
                branch: branch_slug.clone(),
                description: ty_desc,
                sdl: ty_sdl,
                primary_type: ty_name.to_owned(),
                side_effect: None,
                trust,
                tokens: ty_tokens,
            },
        );

        if let ExtendedType::Object(obj) = ext_ty {
            for (fname_node, fdef) in &obj.fields {
                let fname = fname_node.as_str();
                if RESERVED_ROOT_FIELDS.contains(&fname) {
                    continue;
                }
                let ret_name = fdef.ty.inner_named_type().as_str();
                if !is_field_visible(ctx, vis, snap, ty_name, fname, ret_name) {
                    continue;
                }
                let path = format!("{ty_name}.{fname}");
                let fdesc = fdef.description.as_ref().map(|d| d.as_str().to_owned());
                let mut ftokens = split_identifier_and_text_tokens(fname);
                ftokens.extend(split_identifier_and_text_tokens(ty_name));
                if let Some(d) = &fdesc {
                    ftokens.extend(split_identifier_and_text_tokens(d));
                }
                let fsdl = format!("type {ty_name} {{\n  {}\n}}", fdef.to_string().trim());
                map.insert(
                    path.clone(),
                    SearchCandidate {
                        kind: "FIELD",
                        name: fname.to_owned(),
                        path,
                        branch: branch_slug.clone(),
                        description: fdesc,
                        sdl: fsdl,
                        primary_type: ty_name.to_owned(),
                        side_effect: None,
                        trust,
                        tokens: ftokens,
                    },
                );
            }
        }
    }

    map
}

fn kind_allowed(candidate_kind: &str, filter_kinds: Option<&[String]>) -> bool {
    let Some(kinds) = filter_kinds else {
        return true;
    };
    kinds.iter().any(|k| match k.as_str() {
        "operation" => candidate_kind == "OPERATION",
        "type" => candidate_kind == "TYPE",
        "field" => candidate_kind == "FIELD",
        "node_category" => candidate_kind == "NODE_CATEGORY",
        _ => false,
    })
}

fn truncate_sdl_fragment(sdl: &str, primary_type: &str, budget_tokens: usize) -> String {
    if estimate_tokens_gql022(sdl) <= budget_tokens {
        return sdl.to_owned();
    }
    let max_bytes = (budget_tokens.saturating_mul(18)) / 5;
    let cut = floor_utf8_boundary(sdl, max_bytes);
    format!(
        "{}\n# truncated: use __type(name: \"{primary_type}\")",
        sdl[..cut].trim_end()
    )
}

fn score_lexical(query_tokens: &[String], cand_tokens: &[String]) -> f64 {
    if query_tokens.is_empty() || cand_tokens.is_empty() {
        return 0.0;
    }
    let mut matched = 0.0_f64;
    for qt in query_tokens {
        if cand_tokens.iter().any(|ct| ct == qt) {
            matched += 1.0;
        } else if qt.len() >= 3 && cand_tokens.iter().any(|ct| ct.contains(qt.as_str())) {
            matched += 0.8;
        }
    }
    matched / (query_tokens.len() as f64)
}

/// Executes `gap_search` over `ctx.snapshot.index` or the M1 deterministic lexical fallback
/// without ever calling `GraphqlEngine` (`CMP-002`, `GQL-011`, `GQL-020`..`022`, `INV-05`).
pub(crate) fn execute_gap_search(
    inner: &FacadeInner,
    ctx: &RequestContext,
    era: WireEra,
    query: &str,
    kinds: Option<&[String]>,
    limit: usize,
    budget_tokens: usize,
) -> Value {
    let vis = inner.visibility.as_ref();
    let visible_catalog = collect_visible_search_candidates(inner, ctx);

    let (scored_hits, degraded) = if ctx.snapshot.index.element_count() > 0 {
        let fetch_limit = limit.saturating_mul(4).max(10);
        let raw_hits =
            match ctx
                .snapshot
                .index
                .search(&ctx.tenant.scope(), query, None, fetch_limit)
            {
                Ok(h) => h,
                Err(gap_err) => {
                    return build_gap_error_tool_result(
                        &inner.config,
                        era,
                        &ctx.snapshot,
                        gap_err,
                        None,
                    );
                }
            };

        let mut resolved: Vec<(f64, SearchCandidate)> = Vec::new();
        for hit in raw_hits {
            if let Some(buid) = hit.branch_uid
                && let Some(branch) = ctx.snapshot.branches.get(&buid)
                && !is_branch_visible(ctx, vis, branch)
            {
                continue;
            }
            if let Some(cand) = visible_catalog.get(&hit.element_id) {
                if kind_allowed(cand.kind, kinds) {
                    resolved.push((f64::from(hit.fused_score), cand.clone()));
                }
            } else if matches!(hit.kind, ElementKind::NodeCategory)
                && kind_allowed("NODE_CATEGORY", kinds)
            {
                let branch_desc = hit.branch_uid.and_then(|u| ctx.snapshot.branches.get(&u));
                resolved.push((
                    f64::from(hit.fused_score),
                    SearchCandidate {
                        kind: "NODE_CATEGORY",
                        name: hit.element_id.clone(),
                        path: hit.element_id.clone(),
                        branch: branch_desc.map(|b| b.id.as_str().to_owned()),
                        description: None,
                        sdl: format!("# category {}", hit.element_id),
                        primary_type: "GapNode".to_owned(),
                        side_effect: None,
                        trust: branch_desc.map(|b| b.trust),
                        tokens: Vec::new(),
                    },
                ));
            }
            if resolved.len() >= limit {
                break;
            }
        }
        (resolved, false)
    } else {
        let q_tokens = split_identifier_and_text_tokens(query);
        let mut lexical: Vec<(f64, SearchCandidate)> = visible_catalog
            .values()
            .filter(|cand| kind_allowed(cand.kind, kinds))
            .filter_map(|cand| {
                let s = score_lexical(&q_tokens, &cand.tokens);
                (s > 0.0).then(|| (s, cand.clone()))
            })
            .collect();
        lexical.sort_by(|(sa, ca), (sb, cb)| sb.total_cmp(sa).then_with(|| ca.path.cmp(&cb.path)));
        lexical.truncate(limit);
        (lexical, true)
    };

    let abstained = scored_hits
        .iter()
        .all(|(score, _)| *score < ABSTENTION_THRESHOLD);

    let mut total_sdl_bytes = 0_usize;
    let hits_json: Vec<Value> = scored_hits
        .into_iter()
        .map(|(score, cand)| {
            let sdl = truncate_sdl_fragment(&cand.sdl, &cand.primary_type, budget_tokens);
            total_sdl_bytes = total_sdl_bytes.saturating_add(sdl.len());
            json!({
                "score": (score * 10_000.0).round() / 10_000.0,
                "kind": cand.kind,
                "name": cand.name,
                "path": cand.path,
                "branch": cand.branch,
                "description": cand.description,
                "sdl": sdl,
                "sideEffect": cand.side_effect,
                "trust": cand.trust,
            })
        })
        .collect();

    let prelim_hits_str = serde_json::to_string(&hits_json).unwrap_or_default();
    let tokens_estimate = estimate_tokens_gql022(&prelim_hits_str);

    let mut extensions = Map::new();
    if degraded {
        extensions.insert(
            "gap".to_owned(),
            json!({
                "warnings": [
                    {
                        "code": "GAP_DISCOVERY_DEGRADED",
                        "message": "ElementSearch index is empty; using deterministic lexical schema baseline"
                    }
                ]
            }),
        );
    }

    let search_data = json!({
        "__search": {
            "hits": hits_json,
            "tokensEstimate": tokens_estimate,
            "abstained": abstained,
        }
    });

    build_data_tool_result(
        &inner.config,
        era,
        &ctx.snapshot,
        search_data,
        extensions,
        None,
    )
}
